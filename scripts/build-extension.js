const { build } = require('vite');
const path = require('path');
const fs = require('fs');
const { execSync } = require('child_process');

const projectRoot = path.join(__dirname, '..');
const distPath = path.join(projectRoot, 'dist');
const wasmPath = path.join(projectRoot, 'wasm/pkg/bionic_wasm_bg.wasm');
const wasmBytesPath = path.join(projectRoot, 'src/wasm_bytes.ts');

async function buildAll() {
  // 1. Compile Rust WASM crate
  console.log('1. Compiling Rust WASM crate...');
  execSync('wasm-pack build ./wasm --target web', { stdio: 'inherit', cwd: projectRoot });

  // 2. Inline WASM binary to Base64
  console.log('2. Inlining WASM binary...');
  if (!fs.existsSync(wasmPath)) {
    throw new Error(`WASM file not found at ${wasmPath}. Make sure wasm-pack build ran successfully.`);
  }

  const wasmBuffer = fs.readFileSync(wasmPath);
  const wasmBase64 = wasmBuffer.toString('base64');
  const fileContent = `// This file is auto-generated by build-extension.js. Do not edit manually.
export const WASM_BASE64 = "${wasmBase64}";
`;
  fs.writeFileSync(wasmBytesPath, fileContent, 'utf-8');
  console.log(`Successfully inlined WASM (${(wasmBuffer.length / 1024).toFixed(2)} KB)`);

  // Clean dist folder
  if (fs.existsSync(distPath)) {
    fs.rmSync(distPath, { recursive: true, force: true });
  }

  // 3. Build Popup UI
  console.log('3. Building Popup...');
  await build({
    configFile: false,
    build: {
      outDir: 'dist',
      emptyOutDir: false,
      rollupOptions: {
        input: {
          popup: path.resolve(projectRoot, 'src/popup.html'),
        },
        output: {
          entryFileNames: 'src/[name].js',
          assetFileNames: (assetInfo) => {
            if (assetInfo.name === 'popup.css' || assetInfo.name === 'style.css') {
              return 'src/style.css';
            }
            return 'assets/[name]-[hash][extname]';
          }
        }
      }
    }
  });

  // 4. Build Background Script (IIFE format for MV3 background worker compatibility)
  console.log('4. Building Background...');
  await build({
    configFile: false,
    build: {
      outDir: 'dist',
      emptyOutDir: false,
      lib: {
        entry: path.resolve(projectRoot, 'src/bg.ts'),
        name: 'bg',
        formats: ['iife'],
        fileName: () => 'src/bg.js',
      },
      sourcemap: false,
      minify: 'esbuild',
    }
  });

  // 5. Build Content Script (IIFE format for injection safety)
  console.log('5. Building Content Script...');
  await build({
    configFile: false,
    build: {
      outDir: 'dist',
      emptyOutDir: false,
      lib: {
        entry: path.resolve(projectRoot, 'src/convert.ts'),
        name: 'convert',
        formats: ['iife'],
        fileName: () => 'src/convert.js',
      },
      sourcemap: false,
      minify: 'esbuild',
    }
  });

  // 6. Copy static assets
  console.log('6. Copying static assets...');
  if (!fs.existsSync(path.join(distPath, 'src'))) {
    fs.mkdirSync(path.join(distPath, 'src'), { recursive: true });
  }
  const filesToCopy = [
    { src: 'manifest.json', dest: 'manifest.json' },
    { src: 'icon16.png', dest: 'icon16.png' },
    { src: 'icon48.png', dest: 'icon48.png' },
    { src: 'icon128.png', dest: 'icon128.png' },
    { src: 'src/bionic.css', dest: 'src/bionic.css' }
  ];
  filesToCopy.forEach(({ src, dest }) => {
    const srcPath = path.join(projectRoot, src);
    const destPath = path.join(distPath, dest);

    if (fs.existsSync(srcPath)) {
      fs.copyFileSync(srcPath, destPath);
      console.log(`Copied ${src} -> dist/${dest}`);
    } else {
      console.warn(`Warning: Source file ${srcPath} does not exist`);
    }
  });

  console.log('All builds completed successfully!');
}

buildAll().catch((err) => {
  console.error('Build failed:', err);
  process.exit(1);
});
